import { chromium } from "@playwright/test";
const out = process.argv[2];
const b = await chromium.launch({ channel: "chrome" });
const p = await b.newPage({ viewport: { width: 1280, height: 760 } });
const errs = [];
p.on("pageerror", (e) => errs.push(String(e).slice(0, 200)));
await p.goto("http://localhost:5173/#team_chat");
await p.waitForSelector("[data-testid=chat-panel]", { timeout: 20000 });
await p.waitForSelector("[data-testid=group-jazper_team]", { timeout: 10000 });
await p.hover("[data-testid='chan-dm:inbox-watcher']");
await p.waitForTimeout(700);
await p.screenshot({ path: out + "/o1.png" });
await p.mouse.move(900, 400);
await p.fill("textarea[aria-label=Message]", "List the org using your tools and tell me how many groups there are.");
await p.keyboard.press("Enter");
await p.waitForSelector("[data-testid=tool-chip]", { timeout: 40000 });
await p.waitForTimeout(6000);
await p.screenshot({ path: out + "/o2.png" });
await p.click("[data-testid=customize-btn]");
await p.waitForSelector("[data-testid=id-card]");
await p.screenshot({ path: out + "/o3.png" });
console.log("errors", errs);
await b.close();
